"""Generate docs/models.md and docs/metrics.md from the in-app model guide (English).

    uv run python scripts/gen_docs.py
"""

from __future__ import annotations

from pathlib import Path

from portfolio_models import model_guide as g
from portfolio_models.i18n import set_lang
from portfolio_models.models import list_models

DOCS = Path(__file__).resolve().parents[1] / "docs"
HEADER = "<!-- Generated by scripts/gen_docs.py from src/portfolio_models/model_guide.py — do not edit by hand. -->\n\n"


def main() -> None:
    set_lang("en")
    desc = dict(list_models())
    out = [HEADER, "# Model guide\n\n",
           "Every model in Portfolio Models, with its history, core idea, how to read the results, strengths and cautions. "
           "The same guide is available inside the app in Türkçe, English and Deutsch (**📚 Models & guide** tab).\n\n",
           "| Model | Summary |\n|---|---|\n"]
    names = [n for n in desc if n in g.GUIDE]
    out += [f"| [`{n}`](#{n}) | {desc[n]} |\n" for n in names]
    out.append("\n")
    for n in names:
        out.append(f"## {n}\n\n{desc[n]}\n\n{g.markdown(n, 'en')}\n\n")
    if "black_litterman" in g.GUIDE:
        out.append(f"## Black-Litterman\n\n{g.markdown('black_litterman', 'en')}\n\n")
    (DOCS / "models.md").write_text("".join(out))
    (DOCS / "metrics.md").write_text(
        HEADER + "# Metrics glossary\n\nWhat every number in the backtest and portfolio tables means.\n\n"
        + g.metrics_markdown("en") + "\n"
    )
    print("wrote docs/models.md, docs/metrics.md")


if __name__ == "__main__":
    main()
